log = []


def files(pattern):
    return sorted(glob.glob(os.path.join(DATA, pattern)))


def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def save(p, d):
    with open(p, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write("\n")


def sub(label, pattern, old, new):
    """Substring replace inside step title/text/warning and quiz strings."""
    n = 0
    for p in files(pattern):
        raw = open(p, encoding="utf-8").read()
        d = load(p)
        changed = False
        for s in d.get("steps", []):
            for k in ("title", "text", "warning"):
                if s.get(k) and old in s[k]:
                    s[k] = s[k].replace(old, new)
                    changed = True
        for q in d.get("questions", []):
            for k in ("question", "explanation"):
                if old in q[k]:
                    q[k] = q[k].replace(old, new)
                    changed = True
            if any(old in a for a in q["answers"]):
                q["answers"] = [a.replace(old, new) for a in q["answers"]]
                changed = True
        if changed:
            save(p, d)
            n += 1
    log.append(("OK" if n else "CHECK", label, n))


def step(label, pattern, num, text, title=None, warning=False, warning_text=None):
    """Replace step number `num` (1-based) in every file matching pattern."""
    n = 0
    for p in files(pattern):
        d = load(p)
        s = d["steps"][num - 1]
        s["text"] = text
        if title:
            s["title"] = title
        if warning:
            s["warning"] = warning_text
        save(p, d)
        n += 1
    log.append(("OK" if n else "CHECK", label, n))


def quiz(label, pattern, q_contains, correct_text=None, explanation=None):
    n = 0
    for p in files(pattern):
        d = load(p)
        hit = False
        for q in d["questions"]:
            if q_contains in q["question"]:
                if correct_text:
                    q["answers"][q["correct"]] = correct_text
                if explanation:
                    q["explanation"] = explanation
                hit = True
        if hit:
            save(p, d)
            n += 1
    log.append(("OK" if n else "CHECK", label, n))


